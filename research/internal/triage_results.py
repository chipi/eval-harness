#!/usr/bin/env python3
"""The table in TRIAGE_RESULTS_LIVE.md, generated from the harness: the triage goal's rows exactly as the
catalog and `evh goals --goal triage_orrery` rank them (one row per arm, a re-score standing in for the run
it re-read), with the arms' other measures beside them. Only the text between the two markers is rewritten;
the notes around it are written by hand.

    harness/.venv/bin/python research/internal/triage_results.py          # rewrite the table
    harness/.venv/bin/python research/internal/triage_results.py --check  # exit 1 when it is out of date
"""

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "harness"))
from evaluation_harness import catalog_build as cb  # noqa: E402
from evaluation_harness.catalog_adapter import load_catalog_adapter  # noqa: E402

DOC = HERE / "TRIAGE_RESULTS_LIVE.md"
GOAL, DATASET = "triage_orrery", "orrery_triage_v1_labelled"
START, END = "<!-- generated by triage_results.py: start -->", "<!-- generated by triage_results.py: end -->"
WHERE = {"x3": "X3 (AMD)", "dgx": "DGX (NVIDIA)", "mac": "Mac (M4 Pro)"}
HEADS = [
    "#", "model", "where", "passes", "cost @5", "@3", "@10", "misses", "false alarms",
    "model's own cost @5", "no decision", "$ / decision", "s / decision", "ceiling",
]  # fmt: skip


def _count(means: dict, k: str) -> str:
    """`k`'s count, from its rate and the items it is a rate of: "1 / 34"."""
    if k not in means:
        return "—"
    rate, n = means[k]
    return f"{round(rate * n)} / {n}"


def _num(means: dict, k: str, fmt: str, scale: float = 1.0) -> str:
    return format(means[k][0] * scale, fmt) if k in means else "—"


def _model_where(label: str, machine: str) -> tuple[str, str]:
    name = label.split(" · ")[0].removeprefix("triage_").removesuffix("_v1")
    for m, where in WHERE.items():
        if name.startswith(f"local_{m}_"):
            return name.removeprefix(f"local_{m}_"), where
    if name.startswith("stub_"):
        return name, "no model (a fixed answer)"
    hosted = name.startswith("hosted_")
    return name.removeprefix("hosted_"), "OpenRouter (open weights)" if hosted else "OpenRouter"


def table() -> str:
    """The table, as Markdown."""
    A = load_catalog_adapter(None)
    by_ds = cb.collect(A)
    goal = next(g for g in A.goals() if g["goal_id"] == GOAL)
    limit = goal["success_criteria"]["axes"]["false_alarm"]["limit"]
    ans = next(x for x in cb.goal_answers(goal, by_ds) if x["dataset"] == DATASET)
    rows = [r for grp in ans["groups"] if grp["key"].startswith("gold/") for r in grp["rows"]]
    ok = [r for r in rows if r["means"].get("false_alarm", (1, 0))[0] <= limit]
    out_ = [r for r in rows if r not in ok]
    lines = ["| " + " | ".join(HEADS) + " |", "|" + "---|" * len(HEADS)]
    for i, r in enumerate(ok + out_, 1):
        m = r["means"]
        model, where = _model_where(r["label"], r.get("machine") or "")
        model = model.replace("_noreason", " (reasoning off)")
        lines.append(
            "| "
            + " | ".join(
                [
                    str(i),
                    model,
                    where,
                    str(r.get("runs", 1)),
                    f"**{r['mean']:.3f}**",
                    _num(m, "triage_cost_p3", ".3f"),
                    _num(m, "triage_cost_p10", ".3f"),
                    _count(m, "false_dismiss"),
                    _count(m, "false_alarm"),
                    _num(m, "model_triage_cost", ".3f"),
                    _count(m, "no_decision"),
                    _num(m, "cost_usd", ".5f"),
                    _num(m, "latency_ms", ".1f", 1 / 1000),
                    "ok" if r in ok else "out",
                ]
            )
            + " |"
        )
    note = (
        f"Generated from the harness: the goal `{GOAL}` on `{DATASET}`, scored against its gold, in the order the "
        f"catalog ranks them; arms over the false-alarm ceiling ({limit}) last. {ans['notes']} `passes`: the runs "
        "averaged in the row. Counts are of the items each measure is a rate over. `—`: not recorded, because the run "
        "predates the measure (no decision) or bills nothing ($)."
    )
    return "\n".join([note, "", *lines])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="exit 1 when the table is out of date; write nothing"
    )
    args = ap.parse_args()
    doc = DOC.read_text(encoding="utf-8")
    if START not in doc or END not in doc:
        print(f"ERROR: {DOC.name} has no {START} … {END} block", file=sys.stderr)
        return 2
    head, rest = doc.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{table()}\n{END}{tail}"
    if args.check:
        if new != doc:
            print(f"{DOC.name}: the table is out of date (run {Path(__file__).name})")
            return 1
        print(f"{DOC.name}: up to date")
        return 0
    DOC.write_text(new, encoding="utf-8")
    print(f"wrote {DOC.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
