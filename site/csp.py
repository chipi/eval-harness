"""Make the built site servable under a strict Content-Security-Policy.

The prod edge sends `script-src 'self'` and `style-src 'self'` (no 'unsafe-inline'), which
blocks every inline <script> block and every style="" attribute. The page templates use both,
for good local reasons, so instead of banning them in five modules this pass runs last on the
built HTML:

  - each inline <script>…</script> body moves to assets/js/<sha256[:12]>.js, referenced by src
    (same position, same order, so a head script still runs before first paint);
  - each distinct style="" value becomes a class `.s-<sha256[:8]>` in assets/inline.css, its
    declarations marked !important so they still win over the stylesheet, as an inline style
    did.

Content-addressed names: the same script or style on every page is one file and one rule, and
the output is deterministic, so `site-check` (fresh build == committed site/public) still holds.
"""

from __future__ import annotations

import hashlib
import html
import re
from pathlib import Path

_SCRIPT = re.compile(r"<script>(.*?)</script>", re.S)
_STYLE = re.compile(r'\sstyle="([^"]*)"')
_CLASS = re.compile(r'\sclass="([^"]*)"')


def _h(s: str, n: int) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()[:n]


def _important(decls: str) -> str:
    out = []
    for d in html.unescape(decls).split(";"):
        d = d.strip()
        if d:
            out.append(d if d.endswith("!important") else f"{d} !important")
    return "; ".join(out)


def _restyle_tag(tag: str, rules: dict) -> str:
    """One start tag: drop its style="", add the class that carries the same declarations."""
    m = _STYLE.search(tag)
    if not m:
        return tag
    cls = f"s-{_h(m.group(1), 8)}"
    rules[cls] = _important(m.group(1))
    tag = tag[: m.start()] + tag[m.end() :]
    c = _CLASS.search(tag)
    if c:
        return tag[: c.start(1)] + c.group(1) + " " + cls + tag[c.end(1) :]
    return re.sub(r"^<([A-Za-z][\w:-]*)", lambda t: f'<{t.group(1)} class="{cls}"', tag, count=1)


def externalize(out: Path) -> dict:
    """Rewrite every *.html under `out` in place. Returns {"scripts": n, "styles": n}."""
    scripts, rules = {}, {}
    pages = sorted(out.rglob("*.html"))
    for page in pages:
        text = page.read_text(encoding="utf-8")
        up = "../" * (len(page.relative_to(out).parts) - 1)

        def script(m, up=up):
            body = m.group(1)
            name = f"{_h(body, 12)}.js"
            scripts[name] = body
            return f'<script src="{up}assets/js/{name}"></script>'

        text = _SCRIPT.sub(script, text)
        text = re.sub(
            r"<[A-Za-z][^<>]*\sstyle=\"[^\"]*\"[^<>]*>", lambda m: _restyle_tag(m.group(0), rules), text
        )
        if re.search(r'class="[^"]*\bs-[0-9a-f]{8}\b', text) and "assets/inline.css" not in text:
            text = text.replace(
                "</head>", f'<link rel="stylesheet" href="{up}assets/inline.css">\n</head>', 1
            )
        page.write_text(text, encoding="utf-8")
    if scripts:
        (out / "assets" / "js").mkdir(parents=True, exist_ok=True)
        for name, body in scripts.items():
            (out / "assets" / "js" / name).write_text(body.strip() + "\n", encoding="utf-8")
    if rules:
        css = "".join(f".{c} {{ {d} }}\n" for c, d in sorted(rules.items()))
        (out / "assets" / "inline.css").write_text(
            '/* Generated by site/csp.py from the templates\' style="" attributes. Do not edit. */\n' + css,
            encoding="utf-8",
        )
    left = [
        p.name
        for p in pages
        if _SCRIPT.search(p.read_text(encoding="utf-8")) or _STYLE.search(p.read_text(encoding="utf-8"))
    ]
    if left:
        raise SystemExit(f"csp: inline script or style left in {', '.join(left)}")
    return {"scripts": len(scripts), "styles": len(rules)}
