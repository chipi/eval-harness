#!/usr/bin/env python3
"""Download a stratified slice of DBpedia-14 into the harness, sources and GOLD references.

    python examples/classification-dbpedia-14/fetch.py --n 280

STDLIB ONLY, like the other two fetchers: the HuggingFace datasets-server rows API over
HTTPS, no `datasets`, no pyarrow, no pandas.

WHY THE DRAW IS SEEDED-RANDOM AND NOT FIRST-K
  The AG News example took the FIRST k items of each class. That guarantees the small
  slice is a subset of the large one -- which is what `holdout_significance
  --exclude-dataset` needs -- and it does NOT make the small slice representative. It bit
  us immediately: the `keyword` arm scored 0.35 on the 20-item dev slice and 0.67 on the
  200-item measurement slice, a ~3 SD gap, because the first few items of each class are
  not typical of the class.

  So here: shuffle each class's block with a FIXED seed, take the first `per_class` of the
  permutation for the measurement slice, and take the dev slice from the head of that SAME
  permutation. Nesting holds by construction, both slices are random samples, and the same
  --n and --seed reproduce the same items on any machine.

WHY IT SEEKS INSTEAD OF SCANNING
  DBpedia-14's test split is sorted by class -- the first 600 rows are all `Company`. A
  pool-scan like AG News's would need ~70,000 rows to reach the last class. Verified
  instead, at both ends of all 14 blocks: class c occupies offsets [c*5000, (c+1)*5000).
  So this asks for exactly the rows it wants: 14 classes x per_class requests.

  That layout is an assumption about someone else's data, so it is CHECKED at fetch time
  rather than trusted -- every returned row's label must match the class whose block it
  was drawn from, and a mismatch stops the fetch. A re-upload that reorders the split
  would otherwise produce a confidently mislabelled dataset.

WHY THIS DATASET
  It is the second classification corpus, deliberately different from AG News on three
  axes: 14 classes instead of 4, a CLEAN licence, and entity-ontology text rather than
  news. 14 labels also make the model's answer harder to parse and the confusion matrix
  worth reading, both of which AG News barely exercised.

  Expect a CEILING. Published accuracy on DBpedia-14 is ~0.98-0.99 for fine-tuned
  transformer classifiers. If the arms bunch at the top and nothing separates, that is the
  finding, not a failure -- and it is the opposite regime from AG News, where the spread
  was 0.84 to 0.945.

LICENCE -- CLEANER THAN AG NEWS, AND THE REASON THIS ONE EXISTS
  CC-BY-SA 3.0 and GFDL, stated on the dataset card and inherited from Wikipedia. That is
  an actual grant of rights, unlike AG News's `unknown` / non-commercial. Still nothing is
  committed: the slice is downloaded to whoever runs this and is gitignored, because
  redistributing a third-party corpus is a licence question nobody should inherit by
  cloning a repo.

WHY THE REFERENCE IS GOLD
  The labels are DBpedia ontology classes, derived from Wikipedia infoboxes by people
  rather than generated by a model. A reference file here holds one word.

WHAT AN ITEM'S TEXT IS
  `title` and `content` joined with a blank line. The dataset card frames the task as
  "given the content and the title, predict the correct topic", and published baselines
  use both -- so using both is what makes their numbers a check on ours. The join format
  is part of the item, and `source_sha256` freezes it.
"""

from __future__ import annotations

import argparse
import collections
import hashlib
import json
import random
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

# parents[2] is the repo root -> <root>/harness, the harness this example feeds.
ROOT = Path(__file__).resolve().parents[2] / "harness"
ROWS_API = "https://datasets-server.huggingface.co/rows"
DATASET = "fancyzhx/dbpedia_14"
CONFIG = "dbpedia_14"

#: The dataset's own label order. Index IS the stored integer; do not reorder.
LABELS = [
    "Company", "EducationalInstitution", "Artist", "Athlete", "OfficeHolder",
    "MeanOfTransportation", "Building", "NaturalPlace", "Village", "Animal",
    "Plant", "Album", "Film", "WrittenWork",
]

#: Verified at both ends of all 14 blocks on 2026-09-27. Checked again at fetch time.
PER_CLASS_IN_SPLIT = 5000

#: The API caps a single request.
PAGE = 100


#: Retried rather than fatal. A 280-item draw is 280 sequential requests, so the chance of
#: meeting at least one transient gateway error approaches certainty -- this fetcher died
#: on a 502 two thirds of the way through its first real run, losing the whole draw. "Run
#: it again" is not a fix when the failure rate scales with the thing you are fetching.
_TRANSIENT_STATUS = frozenset({500, 502, 503, 504})
_MAX_ATTEMPTS = 7

#: 429 is not a glitch, it is the server saying SLOW DOWN, so it gets its own schedule.
#: Backing off 2,4,8,16,30 — the transient ladder — exhausted six attempts at offset 11 of
#: a 280-item draw and lost the whole fetch. The pause between requests is the actual fix;
#: the longer ladder is what survives a limit that has already been tripped.
_RATE_LIMIT_BACKOFF = (5, 15, 30, 60, 60, 60)

#: A draw of n items is n requests, and the 56-item draw passed while the 280-item draw
#: was refused — so the limiter is on request RATE, not volume. Roughly three per second
#: is what a public API is entitled to expect from a batch job that has all day.
DEFAULT_DELAY = 0.35


def _get(offset: int, length: int, delay: float = DEFAULT_DELAY) -> list[dict]:
    query = urllib.parse.urlencode(
        {"dataset": DATASET, "config": CONFIG, "split": "test",
         "offset": offset, "length": length}
    )
    last = ""
    for attempt in range(1, _MAX_ATTEMPTS + 1):
        try:
            with urllib.request.urlopen(f"{ROWS_API}?{query}", timeout=60) as resp:
                rows = [r["row"] for r in (json.loads(resp.read()).get("rows") or [])]
            time.sleep(delay)
            return rows
        except urllib.error.HTTPError as exc:
            last = f"HTTP {exc.code}"
            if exc.code == 429:
                wait = _RATE_LIMIT_BACKOFF[min(attempt - 1, len(_RATE_LIMIT_BACKOFF) - 1)]
            elif exc.code in _TRANSIENT_STATUS:
                wait = min(2 ** attempt, 30)
            else:
                # A 400 or 404 will not fix itself; retrying wastes a minute before
                # printing the same message.
                break
        except Exception as exc:  # noqa: BLE001 - timeouts, resets, DNS
            last = f"{type(exc).__name__}: {exc}"
            wait = min(2 ** attempt, 30)
        if attempt < _MAX_ATTEMPTS:
            print(f"      {last} at offset {offset}; retry {attempt}/{_MAX_ATTEMPTS - 1} "
                  f"in {wait}s", flush=True)
            time.sleep(wait)
    sys.exit(
        f"datasets-server failed at offset {offset} after {_MAX_ATTEMPTS} attempt(s): {last}\n"
        "  it is an HTTPS API; check connectivity, then retry — or raise --delay."
    )


def fetch_class(label_index: int, wanted: list[int], delay: float = DEFAULT_DELAY) -> list[dict]:
    """Rows at the given WITHIN-CLASS offsets, verifying each one's label.

    Fetched in contiguous runs where the chosen offsets happen to be adjacent, single
    rows otherwise. The verification is the point: a silently reordered split would
    otherwise yield a dataset whose every label is wrong and whose every arm looks broken.
    """
    base = label_index * PER_CLASS_IN_SPLIT
    out: list[dict] = []
    for start in range(0, len(wanted), PAGE):
        for off in wanted[start:start + PAGE]:
            rows = _get(base + off, 1, delay)
            if not rows:
                sys.exit(f"no row at offset {base + off} — the split is smaller than expected")
            row = rows[0]
            if int(row["label"]) != label_index:
                sys.exit(
                    f"LAYOUT CHANGED: offset {base + off} holds "
                    f"{LABELS[int(row['label'])]}, expected {LABELS[label_index]}.\n"
                    "  This fetcher seeks by class block; that assumption no longer holds.\n"
                    "  Do not use the result — every label would be suspect."
                )
            out.append(row)
    return out


def item_text(row: dict) -> str:
    """Title and content, joined. See the module docstring for why both."""
    return f"{str(row['title']).strip()}\n\n{str(row['content']).strip()}"


def item_id(text: str) -> str:
    """Content-addressed id — DBpedia rows carry none of their own."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:40]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=280,
                    help="total items; split evenly across the 14 classes (default: 280)")
    ap.add_argument("--dataset-id", default=None, help="harness dataset_id (default: dbpedia_<n>)")
    ap.add_argument("--seed", type=int, default=20260927,
                    help="draw seed; the same --n and --seed reproduce the same items")
    ap.add_argument("--delay", type=float, default=DEFAULT_DELAY,
                    help=f"seconds between requests (default: {DEFAULT_DELAY}); raise it if 429s persist")
    ap.add_argument("--force", action="store_true", help="overwrite an existing slice")
    args = ap.parse_args()

    if args.n % len(LABELS):
        sys.exit(f"--n must divide by {len(LABELS)} so the classes stay balanced; got {args.n}")
    per_class = args.n // len(LABELS)
    if per_class > PER_CLASS_IN_SPLIT:
        sys.exit(f"--n asks for {per_class} per class; the split holds {PER_CLASS_IN_SPLIT}")

    dataset_id = args.dataset_id or f"dbpedia_{args.n}"
    sources = ROOT / "data" / "sources" / dataset_id
    golds = ROOT / "data" / "references" / "gold" / dataset_id

    if sources.exists() and not args.force:
        print(f"{sources} already exists — pass --force to refetch")
        return 0

    # ONE permutation per class, from a seed that does not depend on --n. That is what
    # makes a smaller slice a strict PREFIX of a larger one: --n 56 takes the first 4 of
    # each class's permutation, --n 280 the first 20, and the 56 are inside the 280.
    # Seeding per class rather than globally keeps that true when the class count changes.
    rows: list[dict] = []
    for index, label in enumerate(LABELS):
        rng = random.Random(f"{args.seed}:{label}")
        permutation = list(range(PER_CLASS_IN_SPLIT))
        rng.shuffle(permutation)
        chosen = sorted(permutation[:per_class])
        print(f"  {label:<24} fetching {per_class} of {PER_CLASS_IN_SPLIT}", flush=True)
        rows.extend(fetch_class(index, chosen, args.delay))

    sources.mkdir(parents=True, exist_ok=True)
    golds.mkdir(parents=True, exist_ok=True)
    for row in rows:
        text = item_text(row)
        item = item_id(text)
        (sources / f"{item}.txt").write_text(text, encoding="utf-8")
        # One word, no trailing newline: a reference differing from the answer by
        # whitespace is a scoring bug waiting to be blamed on the model.
        (golds / f"{item}.txt").write_text(LABELS[int(row["label"])], encoding="utf-8")

    got = collections.Counter(LABELS[int(r["label"])] for r in rows)
    words = sorted(len(item_text(r).split()) for r in rows)
    print(f"\n{len(rows)} item(s) written, {per_class} per class, seed {args.seed}")
    print(f"  texts      {sources}")
    print(f"  gold refs  {golds}")
    print(f"  classes    {len(got)} distinct, all at {min(got.values())}"
          if len(set(got.values())) == 1 else f"  classes    {dict(sorted(got.items()))}")
    print(f"  words      min {words[0]}  median {words[len(words) // 2]}  max {words[-1]}")
    print(f"\n  Balanced by construction, so the majority-class floor is exactly "
          f"{1 / len(LABELS):.4f}.")
    print("\nNext:")
    print(f"  make dataset-create DATASET_ID={dataset_id} ARGS='--source-dir data/sources/{dataset_id}'")
    print(f"  make dataset-materialize DATASET_ID={dataset_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
